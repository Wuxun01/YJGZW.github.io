# -*- coding: utf-8 -*-
"""核对周报Word文档中的数据与CSV源数据一致性"""
import json, os, sys
sys.stdout.reconfigure(encoding='utf-8')

base = r'D:\工作\周报\账外数据'
with open(os.path.join(base, '.temp', 'chart_data.json'), encoding='utf-8') as f:
    csv_data = json.load(f)

errors = []
ok_count = 0

def check(desc, expected, actual):
    global ok_count
    if expected == actual:
        ok_count += 1
        return True
    else:
        errors.append(f'{desc}: 期望={expected} 实际={actual}')
        print(f'  [MISMATCH] {desc}: 期望={expected} 实际={actual}')
        return False

# ===== 一、整体情况 =====
print('===== 一、整体情况 =====')
o = csv_data['overall']
# 8月13日整改指标 1122
check('8月13日整改指标', o[2]['整改指标'], 1122)
# 账外预告警 412
check('8月13日账外预告警', o[2]['告警未立项'], 412)
# 疑似已账外未立项 710
check('8月13日已账外未立项', o[2]['已帐外未立项'], 710)
# 8月7日整改指标 1528
check('8月7日整改指标', o[1]['整改指标'], 1528)
# 周压降 406
check('周压降(1528-1122)', o[1]['整改指标']-o[2]['整改指标'], 406)
# 降幅 26.6%
pct = round(100*(o[1]['整改指标']-o[2]['整改指标'])/o[1]['整改指标'], 1)
check('降幅%', pct, 26.6)
# 7月31日整改指标 2273
check('7月31日整改指标', o[0]['整改指标'], 2273)
# 累计压降 1151
check('累计压降(2273-1122)', o[0]['整改指标']-o[2]['整改指标'], 1151)
# 累计降幅 50.6%
pct2 = round(100*(o[0]['整改指标']-o[2]['整改指标'])/o[0]['整改指标'], 1)
check('累计降幅%', pct2, 50.6)
# 告警 499->412, 压降87, -17.4%
check('8月7日告警', o[1]['告警未立项'], 499)
check('8月13日告警', o[2]['告警未立项'], 412)
check('告警压降', o[1]['告警未立项']-o[2]['告警未立项'], 87)
warn_pct = round(100*(o[1]['告警未立项']-o[2]['告警未立项'])/o[1]['告警未立项'], 1)
check('告警降幅%', warn_pct, 17.4)
# 未立项 1029->710, 压降319, -31.0%
check('8月7日未立项', o[1]['已帐外未立项'], 1029)
check('8月13日未立项', o[2]['已帐外未立项'], 710)
check('未立项压降', o[1]['已帐外未立项']-o[2]['已帐外未立项'], 319)
notset_pct = round(100*(o[1]['已帐外未立项']-o[2]['已帐外未立项'])/o[1]['已帐外未立项'], 1)
check('未立项降幅%', notset_pct, 31.0)
# 已立项 1306
check('8月13日已立项', o[2]['已帐外已立项'], 1306)

# ===== 二、分公司排名 =====
print('\n===== 二、分公司排名 =====')
br = csv_data['branch']
# 前三名
top3 = [
    ('襄阳', 281, 115, -166),
    ('十堰', 94, 13, -81),
    ('宜昌', 83, 9, -74),
]
for name, v07, v13, d in top3:
    b07 = br['8月7日'][name]['整改指标']
    b13 = br['8月13日'][name]['整改指标']
    bd = b13 - b07
    check(f'{name} 8月7日', b07, v07)
    check(f'{name} 8月13日', b13, v13)
    check(f'{name} 周压降', bd, d)

# 后三名
bottom3 = [
    ('荆州', 223, 268, 45),
    ('武汉', 137, 141, 4),
    ('咸宁', 1, 5, 4),
]
for name, v07, v13, d in bottom3:
    b07 = br['8月7日'][name]['整改指标']
    b13 = br['8月13日'][name]['整改指标']
    bd = b13 - b07
    check(f'{name} 8月7日', b07, v07)
    check(f'{name} 8月13日', b13, v13)
    check(f'{name} 周变化', bd, d)

# 明细表 16行
detail = [
    ('襄阳', 281, 115, -166), ('十堰', 94, 13, -81), ('宜昌', 83, 9, -74),
    ('恩施', 197, 139, -58), ('仙桃', 51, 6, -45), ('孝感', 46, 21, -25),
    ('黄冈', 13, 3, -10), ('随州', 35, 35, 0), ('荆门', 5, 5, 0),
    ('黄石', 162, 162, 0), ('天门', 86, 86, 0), ('潜江', 90, 90, 0),
    ('神农架', 19, 19, 0), ('咸宁', 1, 5, 4), ('武汉', 137, 141, 4),
    ('荆州', 223, 268, 45),
]
for name, v07, v13, d in detail:
    b07 = br['8月7日'].get(name, {}).get('整改指标', 0)
    b13 = br['8月13日'].get(name, {}).get('整改指标', 0)
    bd = b13 - b07
    check(f'明细-{name} 8月7日', b07, v07)
    check(f'明细-{name} 8月13日', b13, v13)
    check(f'明细-{name} 周变化', bd, d)

# ===== 三、重点专业 =====
print('\n===== 三、重点专业 =====')
sp = csv_data['specialty']
ftth = [
    ('8月7日告警', sp['8月7日']['FTTH/宽带接入']['告警未立项'], 469),
    ('8月13日告警', sp['8月13日']['FTTH/宽带接入']['告警未立项'], 389),
    ('告警周压降', sp['8月7日']['FTTH/宽带接入']['告警未立项']-sp['8月13日']['FTTH/宽带接入']['告警未立项'], 80),
    ('8月7日未立项', sp['8月7日']['FTTH/宽带接入']['已帐外未立项'], 844),
    ('8月13日未立项', sp['8月13日']['FTTH/宽带接入']['已帐外未立项'], 520),
    ('未立项周压降', sp['8月7日']['FTTH/宽带接入']['已帐外未立项']-sp['8月13日']['FTTH/宽带接入']['已帐外未立项'], 324),
    ('8月7日合计', sp['8月7日']['FTTH/宽带接入']['整改指标'], 1313),
    ('8月13日合计', sp['8月13日']['FTTH/宽带接入']['整改指标'], 909),
    ('合计周压降', sp['8月7日']['FTTH/宽带接入']['整改指标']-sp['8月13日']['FTTH/宽带接入']['整改指标'], 404),
]
for desc, expected, actual in ftth:
    check(desc, expected, actual)

# 占比 99.5%
total_delta = o[1]['整改指标']-o[2]['整改指标']
ftth_delta = sp['8月7日']['FTTH/宽带接入']['整改指标']-sp['8月13日']['FTTH/宽带接入']['整改指标']
ratio = round(100*ftth_delta/total_delta, 1)
check('FTTH占比%', ratio, 99.5)

# ===== 汇总 =====
print('\n========== 周报验证汇总 ==========')
print(f'总核对字段数: {ok_count + len(errors)}')
print(f'匹配: {ok_count}')
print(f'不匹配: {len(errors)}')
if len(errors) == 0:
    print('\n✅ 周报Word文档中所有数据与CSV源数据完全一致！')
else:
    print(f'\n❌ 发现 {len(errors)} 处不一致：')
    for e in errors:
        print(f'  - {e}')
