def branch(row):
    text = ""
    if isinstance(row.get('建设单位'), str):
        text = row['建设单位']
    # 同时看工程名称，若建设单位有地市名则用之
    name = str(row.get('工程名称',''))
    for kw in ['武汉','黄石','襄阳','孝感','咸宁','宜昌','鄂州','荆州','十堰','荆门','黄冈','随州','恩施','仙桃','潜江','天门']:
        if kw in text:
            return kw
    # 从工程名称提取
    for k, v in MAP.items():
        if k in name:
            return v
    # 站点名称也看看
    st = str(row.get('站点名称',''))
    for k, v in MAP.items():
        if k in st:
            return v
    return '其他'

def specialty(name):
    s = str(name)
    if 'FTTH' in s or '光端口' in s or '光缆接入' in s or 'FTTR' in s or '宽带' in s or '补盲' in s or '精投' in s or 'FTTH' in s:
        return 'FTTH/宽带接入'
    if '政企' in s or '专线' in s or 'PON' in s:
        return '政企专线'
    if '无线' in s or '基站' in s or '宏站' in s or 'RRU' in s:
        return '无线网'
    if '低压' in s or '油机' in s or '电源' in s or '机房' in s or '隐患整治' in s:
        return '电源及机房'
    if '主干' in s:
        return '主干光缆'
    if '监控' in s or '平安' in s:
        return '视频监控'
    return '其他'

cols = ['疑似帐外预告警且未立项站点数','疑似已帐外且已立项站点数','疑似已帐外且未立项站点数']

for f in FILES:
    df = pd.read_csv(f, encoding='utf-8-sig')
    print(f"===== {f} 总行数={len(df)} =====")
    tw = df['疑似帐外预告警且未立项站点数'].fillna(0).astype(int).sum()
    ty = df['疑似已帐外且已立项站点数'].fillna(0).astype(int).sum()
    tn = df['疑似已帐外且未立项站点数'].fillna(0).astype(int).sum()
    print(f"整体: 预告警且未立项={tw}, 已帐外且已立项={ty}, 已帐外且未立项={tn}")
    df['分公司'] = df.apply(branch, axis=1)
    g = df.groupby('分公司')[cols].sum().fillna(0).astype(int)
    g['合计'] = g.sum(axis=1)
    g = g.sort_values('合计', ascending=False)
    print("  --- 按分公司 ---")
    print(g.to_string())
    df['专业'] = df['工程名称'].apply(specialty)
    g2 = df.groupby('专业')[cols].sum().fillna(0).astype(int)
